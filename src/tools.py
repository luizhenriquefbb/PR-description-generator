import os
import subprocess
from typing import Optional
from fastmcp import FastMCP

# absolute path to the repository root
BASE_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
TEMP_DIR = os.path.join(BASE_DIR, "temp")

# Ensure the temporary directory exists
os.makedirs(TEMP_DIR, exist_ok=True)

mcp = FastMCP("My git helpers")


def __get_diff_from_pr(base_branch: str, target_branch: str) -> Optional[str]:
    """
    Internal function to get the git diff between two branches and save it to a temporary file.
    The filename is constructed using the target branch name and its latest commit hash for uniqueness.
    Returns the absolute path to the saved diff file, or an error message if the diff cannot be generated
    or if no changes are found.
    """
    command = f"git diff {base_branch} {target_branch}"
    try:
        result = subprocess.run(command, shell=True, capture_output=True, text=True, check=True)

        with open(os.path.join(TEMP_DIR, "diff_output.txt"), "w") as f:
            f.write(result.stdout)
        return result.stdout
    except subprocess.CalledProcessError as e:
        print(f"Error getting diff: {e.stderr}")
        return None


@mcp.tool()
def get_diff_from_pr(base_branch: str, target_branch: str) -> Optional[str]:
    """
    Generates the diff between two branches (only new changes) and saves it to a temporary file.
    Returns the absolute path to the temporary file containing the diff, or an error message.
    """
    return __get_diff_from_pr(base_branch=base_branch, target_branch=target_branch)


@mcp.tool()
def generate_description(branch_base: str, current_branch: str) -> Optional[str]:
    """
    Given the base branch and the current branch, generates a description of the changes made
    in the current branch compared to the base branch. It reads the diff from a temporary file
    generated by `__get_diff_from_pr`.
    Returns the generated prompt string, or an error message if the diff cannot be obtained.
    """
    diff = __get_diff_from_pr(base_branch=branch_base, target_branch=current_branch)
    if diff is None:
        return diff

    prompt = (
        "Generate a concise description of the following code changes:\n"
        "diff is in the file @{temp/diff_output.txt}\n"
        "the template is in the file @{templates/example.md}\n"
        "Save the description in markdown format in temp/description.md."
    )

    return prompt

@mcp.tool()
def generate_commit_message() -> Optional[str]:
    """
    Based on the staged files, generates a concise and descriptive commit message.
    This tool will read the last 10 commits to understand pattern of the massages and will replicate it.
    """

    # Get the last 10 commit messages
    try:
        result = subprocess.run("git log -n 10 --pretty=format:%s", shell=True, capture_output=True, text=True, check=True)
        commit_history = result.stdout
    except subprocess.CalledProcessError as e:
        print(f"Error getting commit history: {e.stderr}")
        return None

    # run command git diff --staged to get the staged changes
    try:
        diff_result = subprocess.run("git diff --staged", shell=True, capture_output=True, text=True, check=True)
        staged_diff = diff_result.stdout
    except subprocess.CalledProcessError as e:
        print(f"Error getting staged diff: {e.stderr}")
        return None

    prompt = (
        "Based on the following commit history:\n"
        f"{commit_history}\n"
        "Generate a concise and descriptive commit message for the currently staged changes.\n"
        "The commit message should follow the same style and format as the previous commits.\n"
        "Save the commit message in temp/commit_message.txt.\n\n"
        f"Staged changes diff:\n{staged_diff}"
    )

    return prompt


if __name__ == "__main__":
    mcp.run()
